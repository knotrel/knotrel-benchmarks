def is_baseline_candidate(manifest: Dict[str, Any]) -> bool:
    """Return whether the manifest declares the two-label baseline/candidate mode."""
    return manifest.get("pilot_design", {}).get("comparison_mode") == BASELINE_CANDIDATE_MODE


def comparison_labels(manifest: Dict[str, Any]) -> Tuple[str, str]:
    """Return the ordered label pair: (A, Aprime) for A/A, (B, C) for baseline/candidate."""
    return BC_LABELS if is_baseline_candidate(manifest) else AA_LABELS


def bundle_ceiling_bytes(manifest: Dict[str, Any]) -> int:
    """Return the session-boundary evidence bundle ceiling for this manifest.

    A/A manifests keep the historical collector constant. B/C manifests must declare
    their own positive ceiling in ``resource_budget.bundle_ceiling_bytes``.
    """
    if not is_baseline_candidate(manifest):
        return PROPOSED_DISK_CEILING_BYTES
    value = manifest.get("resource_budget", {}).get("bundle_ceiling_bytes")
    if type(value) is not int or value <= 0:
        raise ConfigurationValidationError(
            f"Baseline/candidate manifest requires a positive integer resource_budget.bundle_ceiling_bytes, found {value!r}"
        )
    return value


def resolve_launch(
    cell: Dict[str, Any], pair: Dict[str, Any], label: str, baseline_candidate: bool
) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """Return the launch spec and the label-specific cell used to validate its output.

    In A/A mode both labels use the pair argv/cwd/env and the shared cell. In B/C mode
    the label's own launch (binary paths, server identity) overrides the cell so that
    report validation checks the binaries of the label that actually ran.
    """
    if not baseline_candidate:
        return {"argv": pair["argv"], "cwd": pair["cwd"], "env": pair["env"]}, cell
    launch = pair["launch_by_label"][label]
    effective = {key: value for key, value in cell.items() if key != "launch_by_label"}
    effective.update(launch)
    effective["label"] = label
    return launch, effective


def _bc_identities(manifest: Dict[str, Any]) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    prov = manifest.get("provenance")
    if not isinstance(prov, dict):
        raise ConfigurationValidationError("Baseline/candidate manifest missing required 'provenance' object")
    identities = prov.get("comparison_identities")
    if not isinstance(identities, dict) or set(identities) != set(BC_LABELS):
        raise ConfigurationValidationError(
            f"Baseline/candidate provenance must define comparison_identities for exactly {list(BC_LABELS)}"
        )
    shared = prov.get("shared_binaries")
    if not isinstance(shared, dict) or set(shared) != set(SHARED_BINARY_ROLES):
        raise ConfigurationValidationError(
            f"Baseline/candidate provenance must define shared_binaries for exactly {list(SHARED_BINARY_ROLES)}"
        )
    for label in BC_LABELS:
        binaries = identities[label].get("binaries") if isinstance(identities[label], dict) else None
        if not isinstance(binaries, dict) or set(binaries) != set(LABEL_BINARY_ROLES):
            raise ConfigurationValidationError(
                f"Label {label} must define binaries for exactly {list(LABEL_BINARY_ROLES)}"
            )
        for role, binfo in binaries.items():
            if not isinstance(binfo, dict) or not isinstance(binfo.get("path"), str) or not binfo["path"]:
                raise ConfigurationValidationError(f"Label {label} binary {role} must declare a path")
    for role, binfo in shared.items():
        if not isinstance(binfo, dict) or not isinstance(binfo.get("path"), str) or not binfo["path"]:
            raise ConfigurationValidationError(f"Shared binary {role} must declare a path")
    return identities, shared


def _validate_bc_cell_launches(cell: Dict[str, Any], manifest: Dict[str, Any]) -> None:
    """Bind each label's launch to that label's binaries; nothing else may differ."""
    cell_id = cell.get("cell_id")
    for field in ("argv", "cwd", "env"):
        if field in cell:
            raise ConfigurationValidationError(
                f"Cell {cell_id} must not define top-level {field!r} in baseline/candidate mode; use launch_by_label"
            )
    by_label = cell.get("launch_by_label")
    if not isinstance(by_label, dict) or set(by_label) != set(BC_LABELS):
        raise ConfigurationValidationError(f"Cell {cell_id} launch_by_label must define exactly {list(BC_LABELS)}")
    identities, shared = _bc_identities(manifest)
    driver = shared["measure_e2e"]["path"]
    normalized = {}
    for label in BC_LABELS:
        launch = by_label[label]
        if not isinstance(launch, dict):
            raise ConfigurationValidationError(f"Cell {cell_id} label {label} launch must be an object")
        argv, env = launch.get("argv"), launch.get("env")
        if (not isinstance(argv, list) or not argv or not all(isinstance(a, str) for a in argv)
                or not isinstance(launch.get("cwd"), str) or not isinstance(env, dict)):
            raise ConfigurationValidationError(f"Cell {cell_id} label {label} launch requires argv, cwd and env")
        binaries = identities[label]["binaries"]
        if cell.get("type") == "core":
            harness = binaries["knotrel_benchmarks"]["path"]
            if argv[0] != harness or launch.get("executable") != harness:
                raise ConfigurationValidationError(
                    f"Cell {cell_id} label {label} must launch label {label} core harness {harness!r}, found {argv[0]!r}"
                )
            if "server_binary" in launch or "--server-bin" in argv:
                raise ConfigurationValidationError(f"Cell {cell_id} label {label} core launch must not select a server")
            substitutions = {harness: "<label-harness>"}
        elif cell.get("type") == "http":
            server = binaries["knotrel_server"]
            if argv[0] != driver or launch.get("executable") != driver:
                raise ConfigurationValidationError(
                    f"Cell {cell_id} label {label} must launch the shared HTTP driver {driver!r}, found {argv[0]!r}"
                )
            if argv.count("--server-bin") != 1:
                raise ConfigurationValidationError(f"Cell {cell_id} label {label} must pass exactly one --server-bin")
            server_arg_index = argv.index("--server-bin") + 1
            if server_arg_index >= len(argv) or argv[server_arg_index] != server["path"]:
                raise ConfigurationValidationError(
                    f"Cell {cell_id} label {label} --server-bin must select label {label} server {server['path']!r}"
                )
            if launch.get("server_binary") != server["path"] or launch.get("server_binary_sha256") != server.get("sha256"):
                raise ConfigurationValidationError(
                    f"Cell {cell_id} label {label} report expectations must name label {label} server path and SHA-256"
                )
            if env.get("KNOTREL_BIN") != server["path"]:
                raise ConfigurationValidationError(
                    f"Cell {cell_id} label {label} KNOTREL_BIN must select label {label} server"
                )
            substitutions = {server["path"]: "<label-server>"}
        else:
            raise ConfigurationValidationError(f"Cell {cell_id} has unknown type {cell.get('type')!r}")
        normalized[label] = (
            [substitutions.get(arg, arg) for arg in argv],
            {key: substitutions.get(value, value) for key, value in env.items()},
            launch["cwd"] if cell.get("type") == "http" else None,
        )
    if normalized["B"] != normalized["C"]:
        raise ConfigurationValidationError(
            f"Cell {cell_id} B and C launches differ in more than their label binary selection"
        )


def _validate_bc_schedule(
    pilot_design: Dict[str, Any],
    schedule: Dict[str, Any],
    cell_map: Dict[str, Any],
    pairs: List[Dict[str, Any]],
    sessions: List[Dict[str, Any]],
) -> None:
    """Check per-cell and per-session order balance and pair/launch agreement."""
    pairs_per_cell = pilot_design.get("pairs_per_cell")
    per_session = pilot_design.get("pairs_per_cell_per_session")
    if type(pairs_per_cell) is not int or pairs_per_cell <= 0 or pairs_per_cell % 2:
        raise ConfigurationValidationError(f"pairs_per_cell must be a positive even integer, found {pairs_per_cell!r}")
    if type(per_session) is not int or per_session <= 0 or per_session % 2:
        raise ConfigurationValidationError(
            f"pairs_per_cell_per_session must be a positive even integer, found {per_session!r}"
        )
    if per_session * len(sessions) != pairs_per_cell:
        raise ConfigurationValidationError(
            f"pairs_per_cell {pairs_per_cell} != {per_session} pairs x {len(sessions)} sessions"
        )
    if len(pairs) != pairs_per_cell * len(cell_map) or pilot_design.get("total_measured_launches") != 2 * len(pairs):
        raise ConfigurationValidationError(
            f"Baseline/candidate schedule must have {pairs_per_cell} pairs per cell and two launches per pair"
        )
    forward, reverse = list(BC_LABELS), list(reversed(BC_LABELS))
    for pair in pairs:
        if pair.get("labels") not in (forward, reverse):
            raise ConfigurationValidationError(f"Pair {pair.get('pair_id')} labels must be B,C or C,B")
        if pair.get("session") not in range(len(sessions)):
            raise ConfigurationValidationError(f"Pair {pair.get('pair_id')} has invalid session {pair.get('session')!r}")
        if pair.get("cell_id") not in cell_map:
            raise ConfigurationValidationError(f"Pair {pair.get('pair_id')} references unknown cell {pair.get('cell_id')!r}")
        for field in ("argv", "cwd", "env"):
            if field in pair:
                raise ConfigurationValidationError(
                    f"Pair {pair['pair_id']} must not define top-level {field!r} in baseline/candidate mode"
                )
        if pair.get("launch_by_label") != cell_map[pair["cell_id"]]["launch_by_label"]:
            raise ConfigurationValidationError(
                f"Pair {pair['pair_id']} launch_by_label does not match cell {pair['cell_id']}"
            )
    for session in sessions:
        session_pairs = [p for p in pairs if p["session"] == session["session_id"]]
        if len(session_pairs) != session.get("pair_count"):
            raise ConfigurationValidationError(
                f"Session {session['session_id']} declares {session.get('pair_count')} pairs, schedule has {len(session_pairs)}"
            )
        for cell_id in cell_map:
            cell_pairs = [p for p in session_pairs if p["cell_id"] == cell_id]
            b_first = sum(1 for p in cell_pairs if p["labels"] == forward)
            if len(cell_pairs) != per_session or b_first * 2 != per_session:
                raise ConfigurationValidationError(
                    f"Cell {cell_id} session {session['session_id']} label imbalance: {b_first} B-then-C, "
                    f"{len(cell_pairs) - b_first} C-then-B (expected {per_session // 2}/{per_session // 2})"
                )


def _validate_qualification_design(manifest: Dict[str, Any], cell_map: Dict[str, Any]) -> None:
    """Enforce the approved v0.3.0 nine-cell matrix, schedule shape and limits (§5.1-§5.6)."""
    pilot_design = manifest["pilot_design"]
    phase = pilot_design.get("phase")
    if phase not in QUALIFICATION_PHASES:
        raise ConfigurationValidationError(f"Qualification phase must be one of {QUALIFICATION_PHASES}, found {phase!r}")
    cell_ids = set(cell_map)
    if phase == "main" and cell_ids != set(QUALIFICATION_CELL_IDS):
        raise ConfigurationValidationError(
            f"Qualification main phase requires exactly the approved 9 cells; found {sorted(cell_ids)}"
        )
    if phase == "extension" and (not cell_ids or not cell_ids <= set(QUALIFICATION_CELL_IDS)):
        raise ConfigurationValidationError(
            f"Qualification extension requires a non-empty subset of the approved cells; found {sorted(cell_ids)}"
        )
    if pilot_design.get("sessions_count") != QUALIFICATION_SESSIONS_COUNT:
        raise ConfigurationValidationError(f"Qualification requires {QUALIFICATION_SESSIONS_COUNT} sessions")
    if pilot_design.get("pairs_per_cell_per_session") != QUALIFICATION_PAIRS_PER_CELL_PER_SESSION:
        raise ConfigurationValidationError(
            f"Qualification requires {QUALIFICATION_PAIRS_PER_CELL_PER_SESSION} pairs per cell per session"
        )
    if bundle_ceiling_bytes(manifest) != QUALIFICATION_BUNDLE_CEILING_BYTES:
        raise ConfigurationValidationError(
            f"Qualification bundle ceiling must be {QUALIFICATION_BUNDLE_CEILING_BYTES} bytes (50 MiB)"
        )
    for cell_id, cell in cell_map.items():
        kind = "core" if cell.get("type") == "core" else cell.get("scenario")
        expected_metric = QUALIFICATION_PRIMARY_METRICS.get(kind)
        if expected_metric is None or cell.get("primary_metric") != expected_metric:
            raise ConfigurationValidationError(
                f"Cell {cell_id} primary_metric must be {expected_metric!r}, found {cell.get('primary_metric')!r}"
            )
        if kind == "standalone-batch":
            argv = cell["launch_by_label"]["B"]["argv"]
            chunk = str(QUALIFICATION_BATCH_WARMUP_CHUNK_SIZE)
            if (cell.get("warmup_chunk_size") != QUALIFICATION_BATCH_WARMUP_CHUNK_SIZE
                    or argv.count("--batch-warmup-chunk-size") != 1
                    or argv[argv.index("--batch-warmup-chunk-size") + 1:][:1] != [chunk]):
                raise ConfigurationValidationError(
                    f"Cell {cell_id} must pass --batch-warmup-chunk-size {chunk} and declare warmup_chunk_size {chunk}"
                )


def _verify_hashed_executable(description: str, binfo: Dict[str, Any]) -> None:
    expected_hash = binfo.get("sha256")
    if not isinstance(expected_hash, str) or not re.fullmatch(r"[0-9a-f]{64}", expected_hash):
        raise ConfigurationValidationError(
            f"{description} SHA-256 is unresolved or malformed ({expected_hash!r}); build binary before execution"
        )
    path = Path(binfo["path"])
    if not path.is_file():
        raise ConfigurationValidationError(f"{description} does not exist: {path}")
    if not os.access(path, os.X_OK):
        raise ConfigurationValidationError(f"{description} is not executable: {path}")
    actual_hash = digest(path)
    if actual_hash != expected_hash:
        raise ConfigurationValidationError(f"{description} SHA-256 mismatch: {actual_hash} != {expected_hash}")


def _checkout_changed_paths(status: str) -> List[str]:
    """Parse ``git status --porcelain`` output whose first line may have lost its leading space."""
    paths = []
    for line in status.splitlines():
        parts = line.strip().split(maxsplit=1)
        paths.append(parts[1] if len(parts) == 2 else line)
    return paths


def derived_lock_disallowed_differences(baseline_text: str, candidate_text: str) -> List[str]:
    """Return lockfile differences other than the knotrel-core package version line.

    Closure plan §5.2: the candidate harness lock may differ from the baseline derived
    lock only in the local ``knotrel-core`` version.
    """
    def normalize(text: str) -> List[str]:
        lines, package = [], None
        for line in text.splitlines():
            if line == "[[package]]":
                package = None
            elif line.startswith("name = "):
                package = line
            if package == 'name = "knotrel-core"' and line.startswith("version = "):
                lines.append("<knotrel-core version>")
            else:
                lines.append(line)
        return lines

    return [
        line for line in difflib.unified_diff(normalize(baseline_text), normalize(candidate_text), lineterm="", n=0)
        if line[:1] in "+-" and not line.startswith(("+++", "---"))
    ]


def _verify_bc_provenance(manifest: Dict[str, Any]) -> None:
    """Verify every label and shared binary hash, checkout identity and lockfile independently."""
    identities, shared = _bc_identities(manifest)
    for label in BC_LABELS:
        identity = identities[label]
        checkouts = identity.get("checkouts")
        lockfiles = identity.get("lockfiles")
        if not isinstance(checkouts, dict) or set(checkouts) != set(LABEL_CHECKOUT_ROLES.values()):
            raise ConfigurationValidationError(
                f"Label {label} checkouts must define exactly {sorted(LABEL_CHECKOUT_ROLES.values())}"
            )
        if not isinstance(lockfiles, dict) or set(lockfiles) != set(LABEL_LOCKFILE_ROLES):
            raise ConfigurationValidationError(f"Label {label} lockfiles must define exactly {list(LABEL_LOCKFILE_ROLES)}")
        for role, binfo in identity["binaries"].items():
            _verify_hashed_executable(f"Label {label} binary {role}", binfo)
            checkout = checkouts[LABEL_CHECKOUT_ROLES[role]]
            if binfo.get("source_commit") != checkout.get("commit"):
                raise ConfigurationValidationError(
                    f"Label {label} binary {role} source_commit {binfo.get('source_commit')!r} "
                    f"does not match checkout commit {checkout.get('commit')!r}"
                )
        hashed_locks = set()
        for role, lock in lockfiles.items():
            path = Path(lock.get("path", ""))
            if not path.is_file():
                raise ConfigurationValidationError(f"Label {label} lockfile {role} not found: {path}")
            if digest(path) != lock.get("sha256"):
                raise ConfigurationValidationError(
                    f"Label {label} lockfile {role} hash mismatch: {digest(path)} != {lock.get('sha256')}"
                )
            hashed_locks.add(path.resolve())
        for role, checkout in checkouts.items():
            path = Path(checkout.get("path", ""))
            commit = checkout.get("commit")
            if not isinstance(commit, str) or not re.fullmatch(r"[0-9a-f]{40}", commit):
                raise ConfigurationValidationError(f"Label {label} checkout {role} commit must be a full SHA")
            if not path.is_dir():
                raise ConfigurationValidationError(f"Label {label} checkout {role} not found: {path}")
            head = command(["git", "rev-parse", "HEAD"], cwd=path)
            if head != commit:
                raise ConfigurationValidationError(f"Label {label} checkout {role} commit mismatch: {head} != {commit}")
            permitted = set(checkout.get("permitted_changes", []))
            if not permitted <= PERMITTED_CHECKOUT_CHANGES:
                raise ConfigurationValidationError(
                    f"Label {label} checkout {role} may only permit {sorted(PERMITTED_CHECKOUT_CHANGES)} changes"
                )
            for changed in _checkout_changed_paths(command(["git", "status", "--porcelain"], cwd=path)):
                if changed not in permitted:
                    raise ConfigurationValidationError(
                        f"Label {label} checkout {role} must be clean; unexpected change {changed!r}"
                    )
                if (path / changed).resolve() not in hashed_locks:
                    raise ConfigurationValidationError(
                        f"Label {label} checkout {role} permitted change {changed!r} is not a hashed lockfile"
                    )
    for role, binfo in shared.items():
        _verify_hashed_executable(f"Shared binary {role}", binfo)
    harness_commits = {identities[label]["binaries"]["knotrel_benchmarks"].get("source_commit") for label in BC_LABELS}
    if len(harness_commits) != 1:
        raise ConfigurationValidationError(
            f"B and C core harnesses must be built from the same harness commit, found {sorted(map(str, harness_commits))}"
        )
    differences = derived_lock_disallowed_differences(
        Path(identities["B"]["lockfiles"]["benchmarks_lock_derived"]["path"]).read_text(encoding="utf-8"),
        Path(identities["C"]["lockfiles"]["benchmarks_lock_derived"]["path"]).read_text(encoding="utf-8"),
    )
    if differences:
        raise ConfigurationValidationError(
            "Derived harness lockfiles differ beyond the knotrel-core version line: " + "; ".join(differences[:6])
        )


def validate_inputs(
    manifest: Dict[str, Any],
    schedule: Dict[str, Any],
    check_provenance: bool = True,
) -> Dict[str, Any]:
    """Strictly validate manifest, schedule, and filesystem provenance.

    Raises ConfigurationValidationError if any inconsistency, schema error,
    or unexpected git/binary state is detected.
    """
    if not manifest.get("schema", "").startswith("knotrel-p0-pilot-manifest"):
        raise ConfigurationValidationError(f"Invalid manifest schema: {manifest.get('schema')}")
    if not schedule.get("schema", "").startswith("knotrel-p0-pilot-schedule"):
        raise ConfigurationValidationError(f"Invalid schedule schema: {schedule.get('schema')}")

    pilot_design = manifest.get("pilot_design", {})
    manifest_cells = pilot_design.get("cells", [])
    total_cells = pilot_design.get("total_cells")
    total_pairs = pilot_design.get("total_pairs")
    total_measured_runs = pilot_design.get("total_measured_launches")

    if total_cells is None or total_cells != len(manifest_cells):
        raise ConfigurationValidationError(
            f"Manifest total_cells {total_cells} does not match cells array length {len(manifest_cells)}"
        )

    # For the approved baseline pilot plan, enforce the historical 31/186/372 constants
    if manifest.get("checkpoint") == "P0-AA-Pilot-Plan":
        if total_cells != TOTAL_CELLS:
            raise ConfigurationValidationError(
                f"Expected {TOTAL_CELLS} cells in manifest, found {total_cells}"
            )
        if total_pairs != TOTAL_PAIRS:
            raise ConfigurationValidationError(
                f"Expected {TOTAL_PAIRS} pairs in manifest, found {total_pairs}"
            )
        if total_measured_runs != TOTAL_MEASURED_RUNS:
            raise ConfigurationValidationError(
                f"Expected {TOTAL_MEASURED_RUNS} measured runs in manifest, found {total_measured_runs}"
            )

    if schedule.get("total_cells") != total_cells:
        raise ConfigurationValidationError(
            f"Expected {total_cells} cells in schedule, found {schedule.get('total_cells')}"
        )
    if schedule.get("total_pairs") != total_pairs:
        raise ConfigurationValidationError(
            f"Expected {total_pairs} pairs in schedule, found {schedule.get('total_pairs')}"
        )
    if schedule.get("total_measured_runs") != total_measured_runs:
        raise ConfigurationValidationError(
            f"Expected {total_measured_runs} runs in schedule, found {schedule.get('total_measured_runs')}"
        )

    cell_map = {c["cell_id"]: c for c in manifest_cells}
    if len(cell_map) != total_cells:
        raise ConfigurationValidationError("Duplicate cell_id detected in manifest cells array")

    pairs = schedule.get("pairs", [])
    if len(pairs) != total_pairs:
        raise ConfigurationValidationError(f"Schedule pairs array length is {len(pairs)}, expected {total_pairs}")
    pair_ids = [p["pair_id"] for p in pairs]
    if pair_ids != list(range(total_pairs)):
        raise ConfigurationValidationError(
            f"Schedule pair_id sequence must be contiguous 0..{total_pairs - 1} without duplicates"
        )

    # Validate sessions
    sessions = schedule.get("sessions", [])
    expected_sessions_count = pilot_design.get("sessions_count", SESSIONS_COUNT)
    if len(sessions) != expected_sessions_count:
        raise ConfigurationValidationError(f"Expected {expected_sessions_count} sessions, found {len(sessions)}")

    session_seeds = pilot_design.get("session_seeds", list(SESSION_SEEDS))
    expected_pairs_per_session = total_pairs // expected_sessions_count
    for s_idx, s in enumerate(sessions):
        if s.get("session_id") != s_idx:
            raise ConfigurationValidationError(f"Session {s_idx} has mismatched id: {s.get('session_id')}")
        if s_idx < len(session_seeds) and s.get("seed") != session_seeds[s_idx]:
            raise ConfigurationValidationError(
                f"Session {s_idx} seed mismatch: {s.get('seed')} != {session_seeds[s_idx]}"
            )
        pair_cnt = s.get("pair_count", s.get("pairs_count"))
        if pair_cnt != expected_pairs_per_session:
            raise ConfigurationValidationError(
                f"Session {s_idx} pair_count mismatch: {pair_cnt} != {expected_pairs_per_session}"
            )

    baseline_candidate = is_baseline_candidate(manifest)
    if baseline_candidate:
        if not schedule.get("schema", "").startswith("knotrel-p0-pilot-schedule-bc"):
            raise ConfigurationValidationError(
                f"Baseline/candidate manifest requires a knotrel-p0-pilot-schedule-bc schedule, found {schedule.get('schema')!r}"
            )
        bundle_ceiling_bytes(manifest)
        for cell in cell_map.values():
            _validate_bc_cell_launches(cell, manifest)
        _validate_bc_schedule(pilot_design, schedule, cell_map, pairs, sessions)
        if pilot_design.get("qualification_protocol") == QUALIFICATION_PROTOCOL:
            _validate_qualification_design(manifest, cell_map)
        elif manifest.get("checkpoint", "").startswith("v0.3.0-Qualification"):
            raise ConfigurationValidationError(
                f"v0.3.0 qualification manifests must declare qualification_protocol {QUALIFICATION_PROTOCOL!r}"
            )
    elif schedule.get("schema", "").startswith("knotrel-p0-pilot-schedule-bc"):
        raise ConfigurationValidationError("Baseline/candidate schedule requires a baseline_candidate manifest")

    # Validate label balance and exact correspondence of argv/cwd/env per cell
    for cell_id, cell in ({} if baseline_candidate else cell_map).items():
        cell_pairs = [p for p in pairs if p["cell_id"] == cell_id]
        if len(cell_pairs) != 6:
            raise ConfigurationValidationError(
                f"Cell {cell_id} must have exactly 6 scheduled pairs, found {len(cell_pairs)}"
            )
        a_first = sum(1 for p in cell_pairs if p["labels"] == ["A", "Aprime"])
        aprime_first = sum(1 for p in cell_pairs if p["labels"] == ["Aprime", "A"])
        if a_first != 3 or aprime_first != 3:
            raise ConfigurationValidationError(
                f"Cell {cell_id} label imbalance: {a_first} A-then-Aprime, {aprime_first} Aprime-then-A (expected 3/3)"
            )
        for p in cell_pairs:
            if p["cwd"] != cell["cwd"]:
                raise ConfigurationValidationError(
                    f"Cell {cell_id} pair {p['pair_id']} cwd mismatch: {p['cwd']} != {cell['cwd']}"
                )
            if p["argv"] != cell["argv"]:
                raise ConfigurationValidationError(
                    f"Cell {cell_id} pair {p['pair_id']} argv mismatch: {p['argv']} != {cell['argv']}"
                )
            if p["env"] != cell["env"]:
                raise ConfigurationValidationError(
                    f"Cell {cell_id} pair {p['pair_id']} env mismatch: {p['env']} != {cell['env']}"
                )

    if check_provenance and baseline_candidate:
        _verify_bc_provenance(manifest)
    elif check_provenance:
        prov = manifest.get("provenance")
        if not isinstance(prov, dict):
            raise ConfigurationValidationError("Manifest missing required 'provenance' object")

        # Validate baseline binaries existence, permissions, and SHA-256 digests
        binaries = prov.get("binaries")
        if not isinstance(binaries, dict):
            raise ConfigurationValidationError("Manifest provenance missing required 'binaries' object")

        for name, binfo in binaries.items():
            if not isinstance(binfo, dict):
                raise ConfigurationValidationError(f"Binary {name} entry in provenance must be an object")
            expected_hash = binfo.get("sha256")
            if not expected_hash or str(expected_hash).startswith("UNRESOLVED"):
                raise ConfigurationValidationError(
                    f"Binary {name} SHA-256 is unresolved ({expected_hash!r}); build binary before execution"
                )
            bpath_str = binfo.get("path")
            if not bpath_str:
                raise ConfigurationValidationError(f"Binary {name} missing 'path' in provenance")
            bpath = Path(bpath_str)
            if not bpath.is_file():
                raise ConfigurationValidationError(f"Baseline binary {name} does not exist: {bpath}")
            if not os.access(bpath, os.X_OK):
                raise ConfigurationValidationError(f"Baseline binary {name} is not executable: {bpath}")
            actual_hash = digest(bpath)
            if actual_hash != expected_hash:
                raise ConfigurationValidationError(
                    f"Baseline binary {name} SHA-256 mismatch: {actual_hash} != {expected_hash}"
                )

        # Validate git revisions and working tree states
        for req_field in (
            "knotrel_baseline_checkout",
            "knotrel_benchmarks_checkout",
            "knotrel_baseline_commit",
            "knotrel_benchmarks_commit",
        ):
            if req_field not in prov or not prov[req_field]:
                raise ConfigurationValidationError(
                    f"Manifest provenance missing required field: {req_field!r}"
                )

        k_base = Path(prov["knotrel_baseline_checkout"])
        b_base = Path(prov["knotrel_benchmarks_checkout"])

        if not k_base.is_dir():
            raise ConfigurationValidationError(f"Knotrel baseline checkout directory not found: {k_base}")
        if not b_base.is_dir():
            raise ConfigurationValidationError(f"Benchmarks baseline checkout directory not found: {b_base}")

        k_head = command(["git", "rev-parse", "HEAD"], cwd=k_base)
        expected_k_head = prov["knotrel_baseline_commit"]
        if k_head != expected_k_head:
            raise ConfigurationValidationError(
                f"Knotrel baseline commit mismatch: {k_head} != {expected_k_head}"
            )
        k_status = command(["git", "status", "--porcelain"], cwd=k_base)
        if k_status:
            raise ConfigurationValidationError(
                f"Knotrel baseline checkout must be clean; found git status: {k_status!r}"
            )

        b_head = command(["git", "rev-parse", "HEAD"], cwd=b_base)
        expected_b_head = prov["knotrel_benchmarks_commit"]
        if b_head != expected_b_head:
            raise ConfigurationValidationError(
                f"Benchmarks baseline commit mismatch: {b_head} != {expected_b_head}"
            )

        # Verify explicitly permitted staged Cargo.lock in baseline benchmarks
        b_unstaged = command(["git", "diff", "--name-only"], cwd=b_base)
        if b_unstaged:
            raise ConfigurationValidationError(
                f"Unexpected unstaged changes in baseline benchmarks: {b_unstaged!r}"
            )
        b_staged = command(["git", "diff", "--cached", "--name-only"], cwd=b_base)
        if b_staged != "Cargo.lock":
            raise ConfigurationValidationError(
                f"Expected only staged Cargo.lock in baseline benchmarks; found: {b_staged!r}"
            )

        # Validate lockfile provenance structure explicitly
        lockfiles = prov.get("lockfiles")
        if not isinstance(lockfiles, dict):
            raise ConfigurationValidationError("Manifest provenance missing required 'lockfiles' object")

        for lf_key in ("knotrel_lock_sha256", "benchmarks_lock_derived_sha256"):
            if lf_key not in lockfiles or not lockfiles[lf_key]:
                raise ConfigurationValidationError(
                    f"Manifest provenance lockfiles missing required field: {lf_key!r}"
                )

        # Verify lockfile hashes
        k_lock = k_base / "Cargo.lock"
        expected_k_lock_sha = lockfiles["knotrel_lock_sha256"]
        if not k_lock.is_file():
            raise ConfigurationValidationError(f"Knotrel baseline lockfile not found: {k_lock}")
        if digest(k_lock) != expected_k_lock_sha:
            raise ConfigurationValidationError(
                f"Knotrel lockfile hash mismatch: {digest(k_lock)} != {expected_k_lock_sha}"
            )

        b_lock = b_base / "Cargo.lock"
        expected_b_lock_sha = lockfiles["benchmarks_lock_derived_sha256"]
        if not b_lock.is_file():
            raise ConfigurationValidationError(f"Benchmarks baseline lockfile not found: {b_lock}")
        if digest(b_lock) != expected_b_lock_sha:
            raise ConfigurationValidationError(
                f"Benchmarks derived lockfile hash mismatch: {digest(b_lock)} != {expected_b_lock_sha}"
            )

    add_child_info = (
        manifest.get("pilot_design", {})
        .get("additional_child_launches", {})
    )
    if isinstance(add_child_info, dict):
        add_child = add_child_info.get("total_child_servers")
        if add_child is None:
            add_child = (
                add_child_info.get("http_lifecycle_servers", 0)
                + add_child_info.get("http_standalone_batch_servers", 0)
                + add_child_info.get("http_servers", 0)
            )
    else:
        add_child = 0

    expected_total_processes = manifest.get("pilot_design", {}).get("total_process_launches")
    if expected_total_processes is not None and expected_total_processes != total_measured_runs + add_child:
        raise ConfigurationValidationError(
            f"Manifest total_process_launches mismatch: {expected_total_processes} != {total_measured_runs + add_child}"
        )

    return {
        "status": "valid",
        "total_cells": total_cells,
        "total_pairs": total_pairs,
        "total_measured_runs": total_measured_runs,
        "total_process_launches": total_measured_runs + add_child,
        "sessions_count": len(sessions),
        "cells": cell_map,
        "labels": comparison_labels(manifest),
        "baseline_candidate": baseline_candidate,
        "bundle_ceiling_bytes": bundle_ceiling_bytes(manifest),
    }


