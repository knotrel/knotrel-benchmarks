def _supporting_metrics(obs_record: Dict[str, Any], cell_info: Dict[str, Any]) -> Dict[str, Any]:
    """Collect the §5.4 supporting metrics recorded for one B/C observation (report only)."""
    parsed = obs_record.get("parsed_metrics") or {}
    if cell_info.get("type", "core") == "core":
        measurements = parsed.get("measurements") or {}
        values = {f"{op}_p99_ns": (measurements.get(op) or {}).get("p99_ns") for op in ("connected", "link", "cut")}
        values["peak_rss_bytes"] = obs_record.get("peak_rss_bytes")
        return values
    exported = parsed.get("exported_metrics") or {}
    if cell_info.get("scenario") == "standalone-batch":
        keys = ("request_latency_p99_ns", "sampled_max_rss_bytes", "requests_per_sec")
    else:
        keys = ("query_latency_p99_ns", "restart_recovery_ms", "import_duration_ms",
                "catchup_duration_ms", "sampled_max_rss_bytes")
    return {key: exported.get(key) for key in keys}


def analyze_pilot(
    observations: List[Dict[str, Any]],
    cell_map: Dict[str, Any],
    labels: Tuple[str, str] = AA_LABELS,
) -> Dict[str, Any]:
    """Compute descriptive exploratory statistics for completed pairs.

    Strict rules:
    - Descriptive paired differences: delta = second label - first label (Aprime - A, or C - B),
      relative = delta / first label value, log-ratio ln(second / first).
    - Order effects: compare delta distribution for each label order.
    - Between-process variability: CV (sigma/mu) and IQR.
    - No automatic percentage gates, no confidence claims, no pooled p99 from averaged percentiles.
    - B/C outcomes (PASS/REGRESSION/INCONCLUSIVE) are not computed here; they are applied
      separately under the pre-approved decision rules.
    """
    first, second = labels
    baseline_candidate = labels == BC_LABELS
    by_cell: Dict[str, List[Dict[str, Any]]] = {}
    for obs in observations:
        by_cell.setdefault(obs["cell_id"], []).append(obs)

    cell_analyses = []
    for cell_id, cell_obs in by_cell.items():
        cell_info = cell_map.get(cell_id, {})
        is_core = cell_info.get("type", "core") == "core"

        # Pair observations by pair_id
        pairs_dict: Dict[int, Dict[str, Any]] = {}
        for obs in cell_obs:
            p_id = obs["pair_id"]
            pairs_dict.setdefault(p_id, {})[obs["label"]] = obs

        paired_deltas = []
        if cell_info.get("primary_metric"):
            metric_key = cell_info["primary_metric"]
        elif is_core:
            metric_key = "workload_wall_ns"
        elif cell_info.get("scenario") == "standalone-batch" or cell_info.get("workload") == "standalone-batch":
            metric_key = "window_duration_ms"
        else:
            metric_key = "time_to_ready_ms"

        def _extract_metric(obs_record: Dict[str, Any], key: str, is_c: bool) -> Optional[float]:
            parsed = obs_record.get("parsed_metrics") or {}
            if is_c:
                return parsed.get(key)
            exported = parsed.get("exported_metrics", {})
            return exported.get(key)

        for p_id, members in pairs_dict.items():
            if first in members and second in members:
                obs_a = members[first]
                obs_ap = members[second]

                val_a = _extract_metric(obs_a, metric_key, is_core)
                val_ap = _extract_metric(obs_ap, metric_key, is_core)

                if val_a is not None and val_ap is not None and val_a > 0:
                    raw_diff = val_ap - val_a
                    rel_diff = raw_diff / val_a
                    log_ratio = math.log(val_ap / val_a)
                    first_label = obs_a["label"] if obs_a["pair_position"] == 0 else obs_ap["label"]
                    delta = {
                        "pair_id": p_id,
                        f"val_{first}": val_a,
                        f"val_{second}": val_ap,
                        "diff": raw_diff,
                        "relative_diff": rel_diff,
                        "log_ratio": log_ratio,
                        "order": f"{first_label}_first",
                    }
                    if baseline_candidate:
                        delta["session"] = obs_a.get("session")
                        delta["supporting"] = {
                            label: _supporting_metrics(members[label], cell_info) for label in labels
                        }
                    paired_deltas.append(delta)

        # Compute summary stats across all observations
        all_vals = []
        for obs in cell_obs:
            v = _extract_metric(obs, metric_key, is_core)
            if v is not None:
                all_vals.append(v)

        cv = None
        iqr = None
        mean_val = None
        median_val = None
        if len(all_vals) >= 2:
            mean_val = statistics.mean(all_vals)
            stdev_val = statistics.stdev(all_vals)
            cv = (stdev_val / mean_val) if mean_val > 0 else None
            sorted_vals = sorted(all_vals)
            q1 = statistics.median(sorted_vals[: len(sorted_vals) // 2])
            q3 = statistics.median(sorted_vals[(len(sorted_vals) + 1) // 2 :])
            iqr = q3 - q1
            median_val = statistics.median(all_vals)

        cell_analyses.append(
            {
                "cell_id": cell_id,
                "type": cell_info.get("type", "core"),
                "primary_metric": metric_key,
                "total_observations": len(cell_obs),
                "pairs_completed": len(paired_deltas),
                "summary": {
                    "mean": mean_val,
                    "median": median_val,
                    "cv": cv,
                    "iqr": iqr,
                },
                "paired_deltas": paired_deltas,
            }
        )

    analysis = {
        "analysis_type": "exploratory_descriptive",
        "methodological_disclaimer": (
            "Descriptive exploratory noise characterization only. No statistical confidence, "
            "hypothesis test power, or equivalence claims are asserted. Automatic percentage "
            "gates (such as CV > 5%) are rejected. Pooled p99 is not computed from averaged percentiles."
        ),
        "cells": cell_analyses,
    }
    if baseline_candidate:
        analysis["labels"] = list(labels)
        analysis["log_ratio_definition"] = "ln(C / B) per pair"
        analysis["decision_status"] = (
            "not_applied: per-cell PASS/REGRESSION/INCONCLUSIVE outcomes require the pre-approved "
            "decision rules and are not computed by the collector"
        )
    return analysis


