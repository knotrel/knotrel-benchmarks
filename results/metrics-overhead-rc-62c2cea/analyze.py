#!/usr/bin/env python3
"""Regenerates the M6.5 metrics-overhead report from the raw artifacts.

Reads `run/observations.jsonl`, verifies the sha256 of every archived child
stream, and writes `analysis/summary.json`, `REPORT.md` and `manifest.json`.
Statistics and verdicts come from `scripts/run_metrics_overhead.py` (the
same functions the collector used for its stopping decision): per round, the
percent change of `on` and `aa` against `off` (positive = slower); paired
median and 95% bootstrap interval (seed 20261115, 10,000 resamples); the A/A
bound is the larger magnitude of the A/A interval's endpoints.

Budget (approved 2026-11-15 before measurement): PASS if median <= 3% and
interval upper bound <= 6%; REGRESSION if the interval lower bound > 3% and
the median exceeds the A/A bound; otherwise INCONCLUSIVE. Final verdicts use
all rounds (primary plus the extension, if it ran).

Usage: python3 analyze.py [--check]

Copy of results/metrics-overhead-20261115/analyze.py for the v0.4.0 RC re-run
(decision G7-V). The only change: the reported measured commit is read from
run/provenance.json instead of the BASELINE_COMMIT constant, and it refuses
any run whose measured tree is not a clean RC_COMMIT checkout.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import statistics
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "scripts"))
sys.dont_write_bytecode = True

import run_metrics_overhead as mo  # noqa: E402

OUTPUTS = ("analysis/summary.json", "REPORT.md", "manifest.json")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1 << 16):
            digest.update(chunk)
    return digest.hexdigest()


def load(root: Path) -> List[Dict[str, Any]]:
    records = [json.loads(line) for line in (root / "run" / "observations.jsonl").read_text().splitlines()]
    for record in records:
        for key in ("stdout", "stderr"):
            if sha256_file(root / "run" / record[f"{key}_path"]) != record[f"{key}_sha256"]:
                raise ValueError(f"hash mismatch for {record[f'{key}_path']}")
        if record["exit_code"] != 0:
            raise ValueError(f"failed observation {record['sequence']}")
    return records


def summarize(root: Path) -> Dict[str, Any]:
    records = load(root)
    run = root / "run"
    timed = [r for r in records if r["section"] == "timed"]
    primary = [r for r in timed if r["phase"] == "primary"]
    table_all = mo.by_scenario(timed, run)
    table_primary = mo.by_scenario(primary, run)
    scenarios = {}
    for scenario in sorted(table_all):
        rounds = table_all[scenario]
        arms = {arm: statistics.median(v[arm] for v in rounds.values() if arm in v) for arm in mo.ARMS}
        scenarios[scenario] = {
            "median_ns_per_request": arms,
            "final": mo.evaluate(rounds),
            "primary_verdict": mo.evaluate(table_primary[scenario])["on"]["verdict"],
        }
    provenance = json.loads((run / "provenance.json").read_text())
    return {
        "schema": f"{mo.SCHEMA}-summary",
        "identity_sha256": provenance["measured_tree"]["identity_sha256"],
        "code_diff_sha256": provenance["measured_tree"]["code_diff_sha256"],
        "untracked_code_files": provenance["measured_tree"]["untracked_code_files"],
        "rounds": {"primary": len({r["round"] for r in primary}),
                   "extension": len({r["round"] for r in timed if r["phase"] == "extension"})},
        "budget": provenance["budget"],
        "binary_sha256": json.loads((run / "binaries.json").read_text())["sha256"],
        "scenarios": scenarios,
    }


def fmt(value: float, digits: int = 2) -> str:
    return f"{value:,.{digits}f}"


def report(summary: Dict[str, Any], root: Path) -> str:
    run = root / "run"
    env = json.loads((run / "environment.json").read_text())
    host = {c["argv"][0]: c["stdout"].strip() for c in env["host"]["commands"]}
    lines = [
        "# M6.5 Metrics Overhead (generated)",
        "",
        "Generated by `analyze.py` from `run/`. Do not edit by hand; regenerate with "
        "`python3 analyze.py`. Narrative: [README.md](README.md).",
        "",
        "## Identity",
        "",
        "| Item | Value |",
        "| --- | --- |",
        f"| knotrel measured commit | `{json.loads((run / 'provenance.json').read_text())['measured_tree']['base_commit']}` |",
        f"| Measured tree identity sha256 | `{summary['identity_sha256']}` |",
        f"| Code diff sha256 (`git diff HEAD -- . ':(exclude)docs' ':(exclude)*.md'`) | `{summary['code_diff_sha256']}` |",
        f"| Untracked code files | {', '.join(f'`{p}`' for p in summary['untracked_code_files'])} |",
        f"| `router-probe` sha256 (all arms) | `{summary['binary_sha256']}` |",
        f"| Toolchain | `{mo.TOOLCHAIN}` |",
        "",
        "## Host",
        "",
        "```text",
        host.get("sysctl", ""),
        host.get("sw_vers", ""),
        "```",
        "",
        "## Design",
        "",
        f"Arms: `off` (binary without `--metrics`), `on` (same binary with `--metrics`), `aa` "
        f"(byte-identical copy, without `--metrics`). Counterbalanced rounds (every order equally often): "
        f"{summary['rounds']['primary']} primary, {summary['rounds']['extension']} extension. "
        f"`router-probe --mode timing --iterations {mo.PROBE_ITERATIONS}`, mimalloc, no tracing subscriber.",
        "",
        f"Budget: median ≤ {summary['budget']['median_pct_max']}% and 95% CI upper bound ≤ "
        f"{summary['budget']['ci95_upper_pct_max']}% ({summary['budget']['approved']}).",
        "",
        "## Results",
        "",
        "Nanoseconds per request (median over rounds). Change = `on` versus `off` of the same round; "
        "positive = slower.",
        "",
        "| Scenario | n | off | on | aa | Paired change [95% CI] | A/A bound | Primary verdict | Final verdict |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    for scenario, data in summary["scenarios"].items():
        final = data["final"]
        arms = data["median_ns_per_request"]
        ci = final["on"]["ci95_pct"]
        lines.append(
            f"| `{scenario}` | {final['n']} | {fmt(arms['off'])} | {fmt(arms['on'])} | {fmt(arms['aa'])} | "
            f"{final['on']['median_pct']:+.2f}% [{ci[0]:+.2f}%, {ci[1]:+.2f}%] | "
            f"±{final['aa']['noise_bound_pct']:.2f}% | {data['primary_verdict']} | **{final['on']['verdict']}** |")
    verdicts = [d["final"]["on"]["verdict"] for d in summary["scenarios"].values()]
    lines += [
        "",
        f"Outcome: {verdicts.count('PASS')} PASS, {verdicts.count('INCONCLUSIVE')} INCONCLUSIVE, "
        f"{verdicts.count('REGRESSION')} REGRESSION of {len(verdicts)} scenarios.",
        "",
    ]
    return "\n".join(lines)


def manifest(root: Path) -> Dict[str, Any]:
    files = []
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        relative = path.relative_to(root).as_posix()
        if relative == "manifest.json" or "__pycache__" in relative:
            continue
        files.append({"path": relative, "bytes": path.stat().st_size, "sha256": sha256_file(path)})
    return {"schema": f"{mo.SCHEMA}-manifest", "files": files}


def check_rc_provenance(root: Path) -> None:
    """Refuse to report anything but a clean RC measured tree (this copy is for G7-V only)."""
    provenance = json.loads((root / "run" / "provenance.json").read_text())
    tree = provenance["measured_tree"]
    if tree["base_commit"] != mo.RC_COMMIT or tree["code_diff_sha256"] != hashlib.sha256(b"").hexdigest() \
            or tree["untracked_code_files"]:
        raise SystemExit(f"not a clean {mo.RC_COMMIT} measured tree: {tree['base_commit']}")
    if provenance.get("probe", {}).get("directory") != mo.PROBE_DIRS[mo.RC_COMMIT]:
        raise SystemExit(f"router-probe was not built from {mo.PROBE_DIRS[mo.RC_COMMIT]}")


def generate(root: Path) -> None:
    check_rc_provenance(root)
    summary = summarize(root)
    (root / "analysis").mkdir(exist_ok=True)
    (root / "analysis" / "summary.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    (root / "REPORT.md").write_text(report(summary, root))
    (root / "manifest.json").write_text(json.dumps(manifest(root), indent=2, sort_keys=True) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.check:
        generate(HERE)
        print(f"wrote {', '.join(OUTPUTS)} in {HERE}")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "campaign"
        shutil.copytree(HERE, copy, ignore=shutil.ignore_patterns(*OUTPUTS[1:], "analysis", "__pycache__"))
        generate(copy)
        differing = [o for o in OUTPUTS if (copy / o).read_bytes() != (HERE / o).read_bytes()]
    if differing:
        print(f"outputs differ from a clean regeneration: {', '.join(differing)}")
        return 1
    print(f"clean regeneration matches committed outputs: {', '.join(OUTPUTS)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
