#!/usr/bin/env python3
"""Render CELLS.md (every CF5 cell and metric, as classified) from analysis-session1.json.

Usage: python3 render_cells.py analysis-session1.json > CELLS.md

Presentation only: it reads the frozen analyzer's output and changes no class.
"""
import json
import math
import sys
from collections import OrderedDict

BLOCK_ORDER = ["V1", "V2", "K1", "K2", "S1", "L1", "S3", "K3", "K4", "L3", "L4", "L2", "V3", "K2x"]


def pct(x):
    return f"{100 * (math.exp(x) - 1):+.1f}%"


def num(v):
    if v is None:
        return "-"
    if abs(v) >= 1000 or float(v).is_integer():
        return f"{round(v):,}".replace(",", " ")
    return f"{v:.4g}"


def main(path):
    data = json.load(open(path))
    cells = data["cells"]
    by_block = OrderedDict((b, []) for b in BLOCK_ORDER)
    for cell_id, cell in cells.items():
        by_block.setdefault(cell["block"], []).append((cell_id, cell))
    out = [
        "# CF5 attempt 1, session 1: every cell",
        "",
        "Generated by `render_cells.py` from `analysis-session1.json` (frozen `analyze_cf5.py`).",
        "Presentation only: no class is changed, merged or dropped.",
        "",
        "- Interval: `[r(7), r(18)]` of the 24 paired log ratios, 97.73 %, shown as percent change",
        "  `exp(x) - 1`. The log ratio is `ln(CF / reference)` for times and tails and",
        "  `ln(reference / CF)` for throughput (`requests_per_s`), so a negative value is always in",
        "  CF's favour. V2 compares the candidate with v1.0.0 for the same engine.",
        "- `δ`: the section 6.1 widening `limit_log` (log units). `without limit`: the class the",
        "  interval alone gives, published for TIMER_LIMITED metrics and never counted.",
        "- Deterministic blocks (K4, L4): CF and reference values in bytes, one run per arm.",
        "- V1, L2 and S3 follow their own protocols (see REPORT.md); their rows carry the",
        "  analyzer's protocol note.",
        "",
    ]
    for block, rows in by_block.items():
        if not rows:
            continue
        out += [f"## {block}", ""]
        timed = any("interval_log" in m for _, c in rows for m in (c.get("metrics") or {}).values())
        if rows and not rows[0][1].get("metrics"):
            for cell_id, cell in rows:
                out.append(f"- **{cell_id}**: {cell['state']}. {cell.get('protocol_note', '')}")
            out.append("")
            continue
        if timed:
            out += ["| Cell | Metric | Class | CF median | Ref median | Interval | δ | Without limit |",
                    "|---|---|---|---|---|---|---|---|"]
        else:
            out += ["| Cell | Metric | Class | CF | Reference |", "|---|---|---|---|---|"]
        for cell_id, cell in sorted(rows):
            for name, m in sorted(cell["metrics"].items()):
                if timed:
                    iv = m.get("interval_log")
                    interval = f"[{pct(iv[0])}, {pct(iv[1])}]" if iv else "-"
                    delta = f"{m['limit_log']:.4f}" if "limit_log" in m else "-"
                    out.append(f"| {cell_id} | {name} | {m['class']} | {num(m.get('cf_median'))} | "
                               f"{num(m.get('ref_median'))} | {interval} | {delta} | "
                               f"{m.get('class_without_limit', '')} |")
                else:
                    out.append(f"| {cell_id} | {name} | {m['class']} | {num(m.get('cf'))} | {num(m.get('ref'))} |")
        out.append("")
    out += ["## Family statements (section 12)", "",
            "| Family | Against | Statement | Cells named by the analyzer |", "|---|---|---|---|"]
    for family, refs in sorted(data["family_statements"].items()):
        for ref, s in sorted(refs.items()):
            named = ", ".join(f"`{c}`" for c in s["named_cells"]) or "-"
            out.append(f"| {family} | {ref} | {s['statement']} | {named} |")
    out += ["", "## Report notes (analyzer)", ""] + [f"- {n}" for n in data["report_notes"]]
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
