#!/usr/bin/env python3
"""Regenerates the re-check report of the one marginal hot-path regression.

Parses `run/` with the hot-path campaign's own parser and statistics
(`results/hot-path-audit-20261114/analyze.py`: `parse_dynamic`, `compare`,
`verdict`), so the verdict rule is identical: confirmed only if the 95%
bootstrap interval of the paired median excludes zero and the median exceeds
the A/A bound. Primary metric `connected_total_ns`; the others are
secondary. Writes `analysis/summary.json`, `REPORT.md` and `manifest.json`;
`--check` verifies byte-identical regeneration.

Usage: python3 analyze.py [--check]
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import shutil
import statistics
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "hot-path-audit-20261114" / "analyze.py"
spec = importlib.util.spec_from_file_location("hot_path_analyze", SOURCE)
hp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(hp)

OUTPUTS = ("analysis/summary.json", "REPORT.md", "manifest.json")
PRIMARY = "connected_total_ns"
METRICS = (PRIMARY, "workload_wall_ns", "link_total_ns", "cut_total_ns")
ORIGINAL = {"median_pct": 2.14, "ci95_pct": [0.64, 4.18], "noise_bound_pct": 2.06, "n": 12}


def summarize(root: Path) -> Dict[str, Any]:
    run = root / "run"
    records = hp.load_observations(run)
    by_metric: Dict[str, Dict[int, Dict[str, float]]] = {m: {} for m in METRICS}
    fingerprints = set()
    for record in records:
        parsed = hp.parse_dynamic((run / record["stdout_path"]).read_text())
        fingerprints.update(parsed["fingerprints"])
        for metric in METRICS:
            by_metric[metric].setdefault(record["round"], {})[record["arm"]] = parsed["metrics"][metric]
    results = {}
    for metric, rounds in by_metric.items():
        comparison = hp.compare(rounds)
        medians = {arm: statistics.median(v[arm] for v in rounds.values()) for arm in ("base", "cand", "aa")}
        results[metric] = {"median_ns": medians, **comparison}
    provenance = json.loads((run / "provenance.json").read_text())
    return {
        "schema": "knotrel-hot-path-recheck-v1-summary",
        "cell": provenance["cell_id"],
        "binaries": provenance["binaries"],
        "source_manifest_sha256": provenance["source_manifest_sha256"],
        "rounds": len({r["round"] for r in records}),
        "trace_fingerprints_identical": len(fingerprints) == 1,
        "primary_metric": PRIMARY,
        "original": ORIGINAL,
        "metrics": results,
    }


def report(summary: Dict[str, Any]) -> str:
    lines = [
        "# Re-check of the Marginal Hot-Path Regression (generated)",
        "",
        "Generated by `analyze.py` from `run/`; regenerate with `python3 analyze.py`. "
        "Narrative: [README.md](README.md).",
        "",
        f"Cell: `{summary['cell']}`. Rounds: {summary['rounds']} counterbalanced (base, cand, aa). "
        f"Trace fingerprints identical across all runs: {summary['trace_fingerprints_identical']}.",
        "",
        "Binaries (exactly those of `results/hot-path-audit-20261114`, verified by sha256):",
        "",
        "| Arm | sha256 |",
        "| --- | --- |",
    ]
    for arm, data in sorted(summary["binaries"].items()):
        lines.append(f"| `{arm}` | `{data['sha256']}` |")
    original = summary["original"]
    lines += [
        "",
        f"Original campaign (n = {original['n']}): `{PRIMARY}` {original['median_pct']:+.2f}% "
        f"[{original['ci95_pct'][0]:+.2f}%, {original['ci95_pct'][1]:+.2f}%], A/A bound "
        f"±{original['noise_bound_pct']:.2f}%, confirmed regression.",
        "",
        "| Metric | Role | n | Base median ns | Candidate median ns | A/A median ns | Paired change [95% CI] | A/A bound | Verdict |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for metric, data in summary["metrics"].items():
        cand = data["cand"]
        ci = cand["ci95_pct"]
        role = "primary" if metric == PRIMARY else "secondary"
        lines.append(
            f"| `{metric}` | {role} | {len(cand['changes_pct'])} | {data['median_ns']['base']:,.0f} | "
            f"{data['median_ns']['cand']:,.0f} | {data['median_ns']['aa']:,.0f} | "
            f"{cand['median_pct']:+.2f}% [{ci[0]:+.2f}%, {ci[1]:+.2f}%] | "
            f"±{data['aa']['noise_bound_pct']:.2f}% | {cand['verdict']} |")
    lines.append("")
    return "\n".join(lines)


def manifest(root: Path) -> Dict[str, Any]:
    files = []
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        relative = path.relative_to(root).as_posix()
        if relative == "manifest.json" or "__pycache__" in relative:
            continue
        files.append({"path": relative, "bytes": path.stat().st_size, "sha256": hp.sha256_file(path)})
    return {"schema": "knotrel-hot-path-recheck-v1-manifest", "files": files}


def generate(root: Path) -> None:
    summary = summarize(root)
    (root / "analysis").mkdir(exist_ok=True)
    (root / "analysis" / "summary.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    (root / "REPORT.md").write_text(report(summary))
    (root / "manifest.json").write_text(json.dumps(manifest(root), indent=2, sort_keys=True) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.check:
        generate(HERE)
        print(f"wrote {', '.join(OUTPUTS)} in {HERE}")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "campaign"
        shutil.copytree(HERE, copy, ignore=shutil.ignore_patterns("REPORT.md", "manifest.json", "analysis",
                                                                  "__pycache__"))
        generate(copy)
        differing = [o for o in OUTPUTS if (copy / o).read_bytes() != (HERE / o).read_bytes()]
    if differing:
        print(f"outputs differ from a clean regeneration: {', '.join(differing)}")
        return 1
    print(f"clean regeneration matches committed outputs: {', '.join(OUTPUTS)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
